package com.example.dbeventservice.dto;

import com.example.dbeventservice.model.PromoterEvent;
import com.fasterxml.jackson.annotation.JsonInclude;

import java.math.BigDecimal;
import java.time.ZoneOffset;

@JsonInclude(JsonInclude.Include.NON_NULL)
public class PromoterEventDTO {
    public Long id;
    public EventSummaryDTO event;
    public PromoterSummaryDTO promoter;
    public int ticketsSold;
    public BigDecimal grossRevenue;
    public BigDecimal commissionRate;
    public BigDecimal commissionEarned;
    public Boolean commissionEnabled;   // will autobox from primitive boolean
    public String commissionActivatedAt;

    public static PromoterEventDTO from(PromoterEvent pe) {
        PromoterEventDTO dto = new PromoterEventDTO();
        dto.id = pe.getId();

        if (pe.getEvent() != null) {
            dto.event = EventSummaryDTO.from(pe.getEvent());
        }
        if (pe.getPromoter() != null) {
            dto.promoter = PromoterSummaryDTO.from(pe.getPromoter());
        }

        // ✅ ticketsSold is primitive int — no null check
        dto.ticketsSold = pe.getTicketsSold();

        dto.grossRevenue = pe.getGrossRevenue();
        dto.commissionRate = pe.getCommissionRate();
        dto.commissionEarned = pe.getCommissionEarned();

        // ✅ boolean getter generated by Lombok is `isCommissionEnabled()`
        dto.commissionEnabled = pe.isCommissionEnabled();

        if (pe.getCommissionActivatedAt() != null) {
            dto.commissionActivatedAt = pe.getCommissionActivatedAt()
                    .atOffset(ZoneOffset.UTC)
                    .toString();
        }
        return dto;
    }
}
